// switch (e não um mapa de componentes): o React Compiler exige componentes
// estáticos, sem escolher o componente durante a renderização.
export function SocialIcon({ network, className }: { network: SocialNetwork; className?: string }) {
  switch (network) {
    case 'instagram':
      return <Instagram className={className} />;
    case 'discord':
      return <DiscordIcon className={className} />;
    case 'email':
      return <Mail className={className} />;
    case 'github':
      return <Github className={className} />;
    case 'x':
      return <Twitter className={className} />;
    case 'linkedin':
      return <Linkedin className={className} />;
    case 'youtube':
      return <Youtube className={className} />;
    case 'bluesky':
      return <Cloud className={className} />;
    case 'mastodon':
      return <AtSign className={className} />;
    case 'telegram':
      return <Send className={className} />;
    case 'rss':
      return <Rss className={className} />;
    default:
      return <Globe className={className} />;
  }
}

// Nome da rede para leitores de tela ("Instagram", "RSS"…).
export function socialName(network: SocialNetwork) {
  return new Map(Object.entries(SOCIAL_LABELS)).get(network) ?? network;
}

export function FeatureIconView({ icon, className }: { icon: FeatureIcon; className?: string }) {
  switch (icon) {
    case 'shield':
      return <Shield className={className} />;
    case 'eye-off':
      return <EyeOff className={className} />;
    case 'book-open':
      return <BookOpen className={className} />;
    case 'heart':
      return <Heart className={className} />;
    case 'mail':
      return <Mail className={className} />;
    case 'code':
      return <Code className={className} />;
    case 'globe':
      return <Globe className={className} />;
    case 'lock':
      return <Lock className={className} />;
    case 'cpu':
      return <Cpu className={className} />;
    case 'users':
      return <Users className={className} />;
    case 'zap':
      return <Zap className={className} />;
    case 'terminal':
      return <Terminal className={className} />;
    case 'coffee':
      return <Coffee className={className} />;
    default:
      return <Sparkles className={className} />;
  }
}

